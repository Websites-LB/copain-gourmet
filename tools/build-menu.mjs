// Rebuilds site/data/menu.js from Copain's Dinesty menu feed.
//   node tools/build-menu.mjs           -> uses tools/menu-raw.json
//   node tools/build-menu.mjs --fetch   -> downloads the latest published menu first
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const rawPath = path.join(here, 'menu-raw.json');
const FEED = 'https://menu.dinestyapp.com/menus/v1/copain/byblos/latest.json';

if (process.argv.includes('--fetch')) {
  const res = await fetch(FEED);
  if (!res.ok) throw new Error(`Menu feed answered ${res.status}`);
  await writeFile(rawPath, await res.text());
}

const raw = JSON.parse(await readFile(rawPath, 'utf8'));
const imgPath = (photo) => (photo ? photo.src.split('quality(70)/')[1] : undefined);
const clean = (s) => (s || '').replace(/\s+/g, ' ').trim();

const menus = {};
for (const menu of raw.menus) {
  menus[menu.name.toLowerCase()] = menu.categories.map((cat) => ({
    name: clean(cat.name),
    items: cat.dishes
      .filter((d) => d.available)
      .map((d) => {
        const item = { n: clean(d.name), p: d.basePrice };
        const desc = clean(d.description);
        if (desc) item.d = desc;
        const img = imgPath(d.photo);
        if (img) item.i = img;
        if (d.kind === 'SET_MENU') item.set = d.inclusions.map((x) => clean(x.text));
        if (d.tags?.length) item.t = d.tags;
        return item;
      }),
  }));
}

const out = `// Generated by tools/build-menu.mjs from the Dinesty feed (menu version ${raw.version}, ${raw.generatedAt.slice(0, 10)}). Do not edit by hand.\nwindow.COPAIN_MENU = ${JSON.stringify(menus)};\n`;
await writeFile(path.join(here, '..', 'site', 'data', 'menu.js'), out);
const count = Object.values(menus).flat().reduce((n, c) => n + c.items.length, 0);
console.log(`menu.js written: ${count} items`);
